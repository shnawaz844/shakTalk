import React, { useState, useCallback } from 'react';
import { View, Text, TouchableOpacity, StyleSheet, ScrollView, ActivityIndicator, Linking, Platform } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { Feather } from '@expo/vector-icons';
import { useUser, useAuth } from '@clerk/clerk-expo';
import { API_URL } from '../config';
import { colors } from '../theme';
import { Alert } from '../utils/alertCompat';
import { CONSENT_VERSION, TERMS_URL, PRIVACY_URL } from '../legal/legal';

/**
 * Shown once after sign-in (and again whenever CONSENT_VERSION changes),
 * before the app can be used. All four boxes must be ticked.
 *
 * The acceptance is saved twice:
 *  - in the user's Clerk profile (unsafeMetadata.consent), which the app reads;
 *  - on the server (POST /user/consent → Clerk publicMetadata, with the
 *    server's own timestamp), which the user cannot edit. This is the record
 *    to rely on if a user ever disputes what they agreed to.
 */
/** Save acceptance of the current terms (Clerk profile + server record). */
export async function saveConsent(user: any, getToken: () => Promise<string | null>, source: 'signup' | 'consent-screen') {
  const consent = { version: CONSENT_VERSION, acceptedAt: new Date().toISOString(), platform: Platform.OS, source };
  // Keep everything else already in the profile (age, gender, onboarding).
  await user.update({ unsafeMetadata: { ...(user.unsafeMetadata || {}), consent } });
  try {
    const token = await getToken();
    if (token) {
      await fetch(`${API_URL}/user/consent`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
        body: JSON.stringify({ version: CONSENT_VERSION, platform: Platform.OS, source }),
      });
    }
  } catch (e: any) {
    console.warn('[Consent] server record failed (non-fatal):', e?.message);
  }
}

const ITEMS: { key: string; text: string; links?: boolean }[] = [
  { key: 'age', text: 'I am 18 years of age or older.' },
  { key: 'terms', text: 'I have read and agree to the Terms of Use and the Privacy Policy.', links: true },
  {
    key: 'ai',
    text: 'I understand that translations are generated by AI, can contain mistakes, and are not an exact or verified record of what anyone said. I will not rely on them as proof of anyone\'s words, identity or consent.',
  },
  {
    key: 'voice',
    text: 'I consent to my voice being processed in real time by ShakTalk and its AI service providers, which may be located outside my country, to translate my calls, and to transcripts of my calls being saved to my account.',
  },
];

export function ConsentScreen() {
  const { user } = useUser();
  const { getToken, signOut } = useAuth();
  const [checked, setChecked] = useState<Record<string, boolean>>({});
  const [saving, setSaving] = useState(false);
  const allChecked = ITEMS.every((i) => checked[i.key]);

  const accept = useCallback(async () => {
    if (!user || !allChecked) return;
    setSaving(true);
    try {
      await saveConsent(user, getToken, 'consent-screen');
      // useUser() re-renders with the new metadata and the app moves on.
    } catch (err: any) {
      Alert.alert('Could not save', err?.message ?? 'Please check your connection and try again.');
    } finally {
      setSaving(false);
    }
  }, [user, allChecked, getToken]);

  const decline = useCallback(() => {
    Alert.alert(
      'Agreement required',
      'ShakTalk can only be used after accepting these terms. You will be signed out.',
      [
        { text: 'Go back', style: 'cancel' },
        { text: 'Sign out', style: 'destructive', onPress: () => { signOut().catch(() => {}); } },
      ],
    );
  }, [signOut]);

  return (
    <SafeAreaView style={styles.container}>
      <ScrollView contentContainerStyle={styles.scroll}>
        <View style={styles.iconWrap}><Feather name="shield" size={26} color={colors.signal} /></View>
        <Text style={styles.title}>Before you start</Text>
        <Text style={styles.subtitle}>
          ShakTalk uses AI to translate your calls live. Please confirm the following to continue.
        </Text>

        {ITEMS.map((item) => {
          const on = !!checked[item.key];
          return (
            <TouchableOpacity
              key={item.key}
              style={[styles.row, on && styles.rowOn]}
              onPress={() => setChecked((c) => ({ ...c, [item.key]: !c[item.key] }))}
              activeOpacity={0.8}
              accessibilityRole="checkbox"
              accessibilityState={{ checked: on }}
            >
              <View style={[styles.box, on && styles.boxOn]}>
                {on && <Feather name="check" size={14} color={colors.signalOnDark} />}
              </View>
              <Text style={styles.rowText}>
                {item.links ? (
                  <>
                    I have read and agree to the{' '}
                    <Text style={styles.link} onPress={() => Linking.openURL(TERMS_URL)}>Terms of Use</Text>
                    {' '}and the{' '}
                    <Text style={styles.link} onPress={() => Linking.openURL(PRIVACY_URL)}>Privacy Policy</Text>.
                  </>
                ) : item.text}
              </Text>
            </TouchableOpacity>
          );
        })}

        <TouchableOpacity
          style={[styles.cta, (!allChecked || saving) && styles.ctaOff]}
          onPress={accept}
          disabled={!allChecked || saving}
          accessibilityRole="button"
        >
          {saving ? <ActivityIndicator color={colors.signalOnDark} /> : <Text style={styles.ctaText}>Agree and continue</Text>}
        </TouchableOpacity>
        <TouchableOpacity onPress={decline} style={styles.declineBtn}>
          <Text style={styles.declineText}>I don't agree</Text>
        </TouchableOpacity>
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, backgroundColor: colors.ink },
  scroll: { padding: 24, paddingBottom: 48 },
  iconWrap: {
    width: 56, height: 56, borderRadius: 16, alignItems: 'center', justifyContent: 'center',
    backgroundColor: 'rgba(47,224,168,0.1)', borderWidth: 1, borderColor: 'rgba(47,224,168,0.3)',
    marginTop: 12, marginBottom: 18,
  },
  title: { color: colors.warm, fontSize: 28, fontWeight: '800', letterSpacing: -0.5 },
  subtitle: { color: colors.muted, fontSize: 15, lineHeight: 22, marginTop: 8, marginBottom: 24 },
  row: {
    flexDirection: 'row', gap: 14, padding: 16, borderRadius: 16, marginBottom: 12,
    backgroundColor: colors.surface, borderWidth: 1, borderColor: colors.hair,
  },
  rowOn: { borderColor: 'rgba(47,224,168,0.35)' },
  box: {
    width: 24, height: 24, borderRadius: 7, borderWidth: 1.5, borderColor: colors.muted,
    alignItems: 'center', justifyContent: 'center', marginTop: 1,
  },
  boxOn: { backgroundColor: colors.signal, borderColor: colors.signal },
  rowText: { flex: 1, color: colors.warm, fontSize: 14.5, lineHeight: 21 },
  link: { color: colors.signal, textDecorationLine: 'underline' },
  cta: {
    marginTop: 16, height: 56, borderRadius: 16, backgroundColor: colors.signal,
    alignItems: 'center', justifyContent: 'center',
  },
  ctaOff: { opacity: 0.4 },
  ctaText: { color: colors.signalOnDark, fontSize: 16, fontWeight: '800' },
  declineBtn: { alignItems: 'center', padding: 16 },
  declineText: { color: colors.muted, fontSize: 14 },
});
